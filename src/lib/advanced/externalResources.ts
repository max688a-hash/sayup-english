export function getResourcesByLevel(level) {
  return EXTERNAL_RESOURCES[level] || [];
}

export const RESOURCE_LEVELS = ['a1', 'a2', 'b1', 'b2', 'c1'];
export const RESOURCE_LEVEL_LABELS = {
  a1: 'A1 入门',
  a2: 'A2 日常',
  b1: 'B1 进阶',
  b2: 'B2 高阶',
  c1: 'C1 母语级',
};

export function getAllResources() {
  return RESOURCE_LEVELS.flatMap((level) =>
    (EXTERNAL_RESOURCES[level] || []).map((r) => ({ ...r, level }))
  );
}

function pickIds(ids) {
  const all = getAllResources();
  return ids.map((id) => all.find((r) => r.id === id)).filter(Boolean);
}

