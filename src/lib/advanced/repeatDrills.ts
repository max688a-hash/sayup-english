export function getDrillsByLevel(level) {
  return REPEAT_DRILLS.filter(d => d.level === level);
}

export function getDrillsByCategory(category) {
  return REPEAT_DRILLS.filter(d => d.category === category);
}

export function getDrillById(id) {
  return REPEAT_DRILLS.find(d => d.id === id);
}

export function getAllCategories() {
  return [...new Set(REPEAT_DRILLS.map(d => d.category))];
}
