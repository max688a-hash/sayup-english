export function getKidsCardImage(word, theme) {
  if (!word) return null;
  if (theme === 'Fruits' && word === 'orange') {
    return require('../assets/kids/orange_fruit.png');
  }
  const direct = KIDS_CARD_IMAGES[word] || KIDS_CARD_IMAGES[String(word).toLowerCase()];
  if (direct) return direct;
  // 场景句 token 常是复数 / 三单：apples→apple、runs→run，避免图文退回无关 emoji
  const stem = stemKidsWord(String(word).toLowerCase());
  if (stem && stem !== word) {
    return KIDS_CARD_IMAGES[stem] || null;
  }
  return null;
}

function stemKidsWord(w) {
  if (KIDS_CARD_IMAGES[w]) return w;
  const rules = [
    [/ies$/, 'y'],       // blueberries → blueberry（若有）
    [/oes$/, 'o'],       // potatoes → potato
    [/ses$/, 's'],
    [/zes$/, 'z'],
    [/xes$/, 'x'],
    [/ches$/, 'ch'],
    [/shes$/, 'sh'],
    [/s$/, ''],          // apples → apple, runs → run
  ];
  for (const [re, rep] of rules) {
    if (re.test(w)) {
      const s = w.replace(re, rep);
      if (KIDS_CARD_IMAGES[s]) return s;
    }
  }
  return w;
}
