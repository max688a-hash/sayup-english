export function countVocab4Words() {
  return VOCAB_THEMES_4.reduce((acc, t) => acc + t.words.length, 0);
}

export function getAllVocab4Words() {
  const all = [];
  for (const t of VOCAB_THEMES_4) {
    for (const w of t.words) all.push({ ...w, themeId: t.id, level: t.level });
  }
  return all;
}
