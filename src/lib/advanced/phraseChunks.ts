// 工具函数：拍平所有 chunks 成一维数组（用于练习/SRS）
export function flattenChunks() {
  const flat = [];
  for (const theme of PHRASE_CHUNKS) {
    for (const c of theme.chunks) {
      flat.push({ ...c, themeId: theme.id, themeZh: theme.themeZh, level: theme.level });
    }
  }
  return flat;
}

export function getChunksByLevel(level) {
  return PHRASE_CHUNKS.filter((t) => t.level === level);
}
