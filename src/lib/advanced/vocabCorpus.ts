export function getVocabByLevel(level) {
  return VOCAB_THEMES.filter((t) => t.level === level);
}

export function getAllVocabWords() {
  const all = [];
  for (const t of VOCAB_THEMES) {
    for (const w of t.words) all.push({ ...w, themeId: t.id, level: t.level });
  }
  return all;
}

export function countAllWords() {
  return VOCAB_THEMES.reduce((acc, t) => acc + t.words.length, 0);
}
